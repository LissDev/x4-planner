import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const directory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => readFile(path.join(directory, file), 'utf8');
const stripExports = source => source.replace(/^export /gm, '');
const stripImports = source => source.replace(/^import .+;\r?\n/gm, '');
const engine = stripExports(await read('src/engine.js'));
const projects = stripExports(await read('src/project-store.js'));
const i18n = stripExports(await read('src/i18n.js'));
const stationI18n = stripExports(stripImports(await read('src/station-i18n.js')));
const catalog = stripExports(stripImports(await read('src/catalog.js')));
const weaponProfile = stripExports(await read('src/weapon-profile.js'));
const shipEngine = stripExports(stripImports(await read('src/ship-engine.js')));
const isCombat = stripExports(stripImports(await read('src/is-combat.js')));
const shipStore = stripExports(stripImports(await read('src/ship-store.js')));
const shipI18n = stripExports(stripImports(await read('src/ship-i18n.js')));
const shipUi = stripExports(stripImports(await read('src/ship-ui.js')));
const app = stripImports(await read('src/app.js'));
const solver = await read('vendor/solver.global.js');
const worker = `${solver}\n${engine}\nself.onmessage = event => {
  try {
    self.postMessage({ result: optimizeStation({ ...event.data, milpSolver: solver }) });
  } catch (error) {
    self.postMessage({ error: error.message });
  }
};`;
const shipFeature = `const createShipUi = (() => {\n${weaponProfile}\n${shipEngine}\n${isCombat}\n${shipStore}\n${shipI18n}\n${shipUi}\nreturn createShipUi;\n})();`;
const bundle = `// Generated by scripts/build-offline.mjs. Edit src files instead.\n${engine}\n${projects}\n${i18n}\n${stationI18n}\n${catalog}\n${shipFeature}\nglobalThis.OPTIMIZER_WORKER_SOURCE = ${JSON.stringify(worker)};\n${app}\n`;
await writeFile(path.join(directory, 'bundle.js'), bundle);
console.log(`Wrote bundle.js (${Buffer.byteLength(bundle)} bytes)`);
