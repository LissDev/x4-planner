export function shipDiagnostic(message, locale = 'en') {
  if (locale !== 'ru') return shipEnglish[message] ?? message;
  const prefix = Object.keys(shipEngineErrors).find(key => message.startsWith(key));
  return prefix ? shipEngineErrors[prefix] + message.slice(prefix.length) : message;
}
